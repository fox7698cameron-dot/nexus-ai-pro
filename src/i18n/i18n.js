// ── Auto-detect language from Accept-Language header ──────────────────────────
export function detectLanguage(acceptLanguage) {
  if (!acceptLanguage) return 'en';
  const langs = acceptLanguage
    .split(',')
    .map(l => l.split(';')[0].trim().toLowerCase().slice(0, 2));
  for (const lang of langs) {
    if (translations[lang]) return lang;
  }
  return 'en';
}

export function getTranslations(lang) {
  return translations[lang] || translations.en;
}

export function t(lang, key) {
  const locale = translations[lang] || translations.en;
  return locale.t[key] || translations.en.t[key] || key;
}

export function getSupportedLanguages() {
  return Object.entries(translations).map(([code, v]) => ({
    code,
    name: v.name,
    locale: v.locale,
    dir: v.dir
  }));
}

export default translations;
