// ─── Locale state ─────────────────────────────────────────────────────────────

let _currentLocale = 'en';

// ─── Locale detection ─────────────────────────────────────────────────────────

/**
 * Parse an Accept-Language header string or navigator.language value and return
 * the best-matching supported locale code.
 * @param {string} header - e.g. "fr-CA,fr;q=0.9,en;q=0.8"
 * @returns {string}
 */
export function detectLocale(header) {
  if (!header) return 'en';
  const supported = Object.keys(translations);
  // Split by comma, strip quality, get base lang codes
  const candidates = header
    .split(',')
    .map((s) => s.trim().split(';')[0].trim().toLowerCase().split('-')[0]);
  for (const c of candidates) {
    if (supported.includes(c)) return c;
  }
  return 'en';
}

// ─── Core translation function ────────────────────────────────────────────────

/**
 * Translate a key in the current locale (or a specified locale).
 * Supports:
 *   - {{param}} interpolation
 *   - count-based pluralization (key_one / key_other)
 *
 * @param {string} key
 * @param {object} [params]
 * @param {string} [locale] - override locale
 * @returns {string}
 */
export function t(key, params = {}, locale) {
  const lang = locale || _currentLocale;
  const dict = translations[lang] || translations['en'];
  const fallback = translations['en'];

  let resolved;

  // Plural resolution: if params.count is defined, try key_one vs key_other
  if (params.count !== undefined) {
    const pluralKey = params.count === 1 ? `${key}_one` : `${key}_other`;
    resolved = dict[pluralKey] ?? fallback[pluralKey] ?? dict[key] ?? fallback[key] ?? key;
  } else {
    resolved = dict[key] ?? fallback[key] ?? key;
  }

  // Interpolation: replace {{param}} placeholders
  return resolved.replace(/\{\{(\w+)\}\}/g, (_, name) =>
    params[name] !== undefined ? String(params[name]) : `{{${name}}}`
  );
}

// ─── Locale management ────────────────────────────────────────────────────────

/**
 * Get the currently active locale.
 * @returns {string}
 */
export function getLocale() {
  return _currentLocale;
}

/**
 * Set the active locale. Falls back to 'en' if unsupported.
 * @param {string} locale
 */
export function setLocale(locale) {
  _currentLocale = translations[locale] ? locale : 'en';
}

// ─── RTL detection ────────────────────────────────────────────────────────────

/**
 * Returns true if the given locale is right-to-left.
 * @param {string} locale
 * @returns {boolean}
 */
export function isRTL(locale) {
  return RTL_LOCALES.has(locale || _currentLocale);
}

// ─── Number / date / currency formatting ─────────────────────────────────────

/**
 * Format a number using the locale's conventions.
 * @param {number} n
 * @param {string} [locale]
 * @returns {string}
 */
export function formatNumber(n, locale) {
  return new Intl.NumberFormat(locale || _currentLocale).format(n);
}

/**
 * Format a date value.
 * @param {Date|string|number} date
 * @param {string} [locale]
 * @param {Intl.DateTimeFormatOptions} [options]
 * @returns {string}
 */
export function formatDate(date, locale, options = {}) {
  const d = date instanceof Date ? date : new Date(date);
  return new Intl.DateTimeFormat(locale || _currentLocale, options).format(d);
}

/**
 * Format a monetary amount.
 * @param {number} amount
 * @param {string} currency - ISO 4217 code, e.g. 'USD'
 * @param {string} [locale]
 * @returns {string}
 */
export function formatCurrency(amount, currency, locale) {
  return new Intl.NumberFormat(locale || _currentLocale, {
    style: 'currency',
    currency,
  }).format(amount);
}

// ─── Language name lookup ─────────────────────────────────────────────────────

/**
 * Get the native name for a language code.
 * @param {string} code
 * @returns {string}
 */
export function getLanguageName(code) {
  return LANGUAGE_NAMES[code] || code;
}

/**
 * Return all supported locales with their native names.
 * @returns {Array<{code: string, name: string, rtl: boolean}>}
 */
export function getSupportedLocales() {
  return Object.keys(LANGUAGE_NAMES).map((code) => ({
    code,
    name: LANGUAGE_NAMES[code],
    rtl: isRTL(code),
  }));
}

// ─── React hook (client-side only) ───────────────────────────────────────────
// This export is intended for React environments. In Node.js it is a no-op
// factory that returns the same API surface so server-side code can import
// without crashing.

let _reactHook = null;

/**
 * React hook: useTranslation()
 * Returns { t, locale, setLocale, isRTL }.
 * When imported in a React environment, uses useState/useCallback for
 * reactive locale updates; otherwise returns a plain object.
 */
export function useTranslation() {
  // Detect React availability
  if (typeof globalThis !== 'undefined' && _reactHook) return _reactHook();

  // Node.js / non-React fallback
  return {
    t: (key, params) => t(key, params),
    locale: _currentLocale,
    setLocale,
    isRTL: () => isRTL(_currentLocale),
  };
}

/**
 * Register a real React hook implementation.
 * Call this from your React entry point:
 *
 *   import { useState, useCallback } from 'react';
 *   import { registerReactHook } from './i18n/index.js';
 *
 *   registerReactHook((useState, useCallback) => () => {
 *     const [locale, _setLocale] = useState(getLocale());
 *     const changeLocale = useCallback((l) => { setLocale(l); _setLocale(l); }, []);
 *     return { t: (k, p) => t(k, p, locale), locale, setLocale: changeLocale, isRTL: () => isRTL(locale) };
 *   });
 */
export function registerReactHook(factory) {
  // The factory receives (useState, useCallback) and returns a hook function
  _reactHook = factory;
}

// ─── Server-side factory ──────────────────────────────────────────────────────

/**
 * Create a scoped i18n instance for server-side use.
 * @param {string} locale
 * @returns {{ t, locale, isRTL, formatNumber, formatDate, formatCurrency }}
 */
export function createI18n(locale) {
  const loc = translations[locale] ? locale : 'en';
  return {
    locale: loc,
    t: (key, params) => t(key, params, loc),
    isRTL: () => isRTL(loc),
    formatNumber: (n) => formatNumber(n, loc),
    formatDate: (d, opts) => formatDate(d, loc, opts),
    formatCurrency: (amount, currency) => formatCurrency(amount, currency, loc),
  };
}

