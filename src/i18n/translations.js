// ── i18n hook ──────────────────────────────────────────────────────────────
const RTL_CODES = new Set(SUPPORTED_LANGUAGES.filter(l => l.dir === 'rtl').map(l => l.code));

export function useI18n(langCode = 'en') {
  const dict = TRANSLATIONS[langCode] || TRANSLATIONS.en;

  function t(key, fallback) {
    return dict[key] || TRANSLATIONS.en[key] || fallback || key;
  }

  function isRTL() {
    return RTL_CODES.has(langCode);
  }

  return { t, isRTL, lang: langCode };
}

// Detect browser language and return closest supported code
export function detectBrowserLanguage() {
  const codes = new Set(SUPPORTED_LANGUAGES.map(l => l.code));
  if (typeof navigator === 'undefined') return 'en';
  for (const lang of navigator.languages || [navigator.language]) {
    if (!lang) continue;
    if (codes.has(lang)) return lang;
    const base = lang.split('-')[0];
    if (codes.has(base)) return base;
  }
  return 'en';
}

// Lightweight auto-translate via server proxy (never exposes API keys to client)
export async function autoTranslate(text, targetLang) {
  if (!text || targetLang === 'en') return text;
  try {
    const res = await fetch('/api/translate', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ text, targetLang }),
    });
    if (!res.ok) return text;
    const data = await res.json();
    return data.translation || text;
  } catch {
    return text;
  }
}
